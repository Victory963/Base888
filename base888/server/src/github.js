"use strict";
// Real GitHub export using the GitHub REST API + a user-supplied Personal Access
// Token (scope: repo). Actually creates a repo and commits files. No fakery:
// without a valid token it fails; with one it really pushes.
const API = "https://api.github.com";

async function gh(path, token, init = {}) {
  return fetch(`${API}${path}`, {
    ...init,
    headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json", "User-Agent": "Base888", "content-type": "application/json", ...(init.headers || {}) }
  });
}

async function exportToGithub({ token, repoName, description, files }) {
  const meRes = await gh("/user", token);
  if (!meRes.ok) throw Object.assign(new Error("GitHub auth failed (check token/scope)"), { status: 401, code: "github_auth_failed" });
  const me = await meRes.json();

  const createRes = await gh("/user/repos", token, { method: "POST", body: JSON.stringify({ name: repoName, description: description || "Generated by Base888", private: false, auto_init: true }) });
  if (!createRes.ok && createRes.status !== 422) {
    throw Object.assign(new Error(`repo create failed: ${await createRes.text()}`), { status: 400, code: "github_repo_failed" });
  }

  const committed = [];
  for (const [path, content] of Object.entries(files)) {
    let sha;
    const existing = await gh(`/repos/${me.login}/${repoName}/contents/${encodeURIComponent(path)}`, token);
    if (existing.ok) { try { sha = (await existing.json()).sha; } catch { /* new file */ } }
    const putRes = await gh(`/repos/${me.login}/${repoName}/contents/${encodeURIComponent(path)}`, token, {
      method: "PUT",
      body: JSON.stringify({ message: `Add ${path} (Base888)`, content: Buffer.from(content).toString("base64"), sha })
    });
    if (!putRes.ok) throw Object.assign(new Error(`commit ${path} failed: ${await putRes.text()}`), { status: 400, code: "github_commit_failed" });
    committed.push(path);
  }
  return { repo: `${me.login}/${repoName}`, url: `https://github.com/${me.login}/${repoName}`, committed };
}

module.exports = { exportToGithub };
